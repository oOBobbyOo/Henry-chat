/** 市场列表(可筛选) */
function buildMcpMarket(filters?: { price?: string; credential?: string; status?: string }): TokenHub.McpMarketResponse {
  let items = MCP_SERVICES
  if (filters?.price && filters.price !== 'all') {
    items = items.filter((s) => s.price_type === filters.price)
  }
  if (filters?.credential && filters.credential !== 'all') {
    items = items.filter((s) => s.credential_type === filters.credential)
  }
  if (filters?.status && filters.status !== 'all') {
    items = items.filter((s) => (filters.status === 'active' ? s.status === 'active' || s.pinned : s.status === 'disabled'))
  }
  return { items }
}

/** 启用 / 禁用 MCP 服务 */
function enableMcp(serviceId: string, enabled: boolean): TokenHub.McpEnableResponse {
  const service = MCP_SERVICES.find((s) => s.id === serviceId)
  if (service && !service.pinned) {
    service.status = enabled ? 'active' : 'disabled'
  }
  return { service_id: serviceId, status: service?.status ?? 'disabled' }
}

